"""
models/workflow.py — WorkflowState and session-level models.

WorkflowState is the shared "blackboard" that LangGraph passes between agents.
Every agent reads from it and writes its outputs back into it.
"""

from __future__ import annotations

from datetime import datetime, timezone
from enum import Enum
from typing import Any, Optional
from pydantic import BaseModel, Field

from models.student import StudentProfile
from models.opportunity import ScholarshipOpportunity


class AgentStatus(str, Enum):
    PENDING = "pending"
    RUNNING = "running"
    DONE = "done"
    FAILED = "failed"
    SKIPPED = "skipped"


class AgentEvent(BaseModel):
    """A single status update emitted by an agent (streamed via SSE)."""
    agent: str
    status: AgentStatus
    message: str
    timestamp: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())
    data: Optional[Any] = None   # optional payload (e.g. partial results)


class SOP(BaseModel):
    """Personalized statement of purpose generated by the Application Coach."""
    draft: str = Field(..., description="The SOP draft text")
    word_count: int
    tailored_for: Optional[str] = Field(
        default=None, description="University/program this SOP is tailored to"
    )
    notes: list[str] = Field(
        default_factory=list,
        description="Tips the coach recommends for improving the SOP",
    )


class ApplicationChecklist(BaseModel):
    """Per-opportunity application checklist."""
    opportunity_id: str
    university_name: str
    program_name: str
    items: list[str] = Field(..., description="Ordered list of action items")
    deadline: Optional[str] = None
    application_url: Optional[str] = None


class WorkflowState(BaseModel):
    """
    The shared state passed through the LangGraph pipeline.

    Think of it as a baton in a relay race — each agent
    enriches it and passes it to the next.
    """

    # ── Input ─────────────────────────────────────────────────
    session_id: str
    student_profile: StudentProfile

    # ── Agent outputs ─────────────────────────────────────────
    opportunities: list[ScholarshipOpportunity] = Field(default_factory=list)
    top_opportunities: list[ScholarshipOpportunity] = Field(default_factory=list)
    sop: Optional[SOP] = None
    checklists: list[ApplicationChecklist] = Field(default_factory=list)

    # ── Workflow metadata ─────────────────────────────────────
    events: list[AgentEvent] = Field(default_factory=list)
    agent_statuses: dict[str, AgentStatus] = Field(
        default_factory=lambda: {
            "researcher": AgentStatus.PENDING,
            "eligibility_verifier": AgentStatus.PENDING,
            "opportunity_matcher": AgentStatus.PENDING,
            "application_coach": AgentStatus.PENDING,
        }
    )
    errors: dict[str, str] = Field(
        default_factory=dict,
        description="Agent name → error message for any failed agents",
    )
    is_demo: bool = Field(
        default=False,
        description="True if running in demo mode (no real APIs called)",
    )
    started_at: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())
    completed_at: Optional[str] = None

    def emit(self, agent: str, status: AgentStatus, message: str, data: Any = None) -> AgentEvent:
        """Convenience method to record an agent event."""
        event = AgentEvent(agent=agent, status=status, message=message, data=data)
        self.events.append(event)
        self.agent_statuses[agent] = status
        return event


class ResearchRequest(BaseModel):
    """HTTP request body for POST /api/research."""
    student_profile: StudentProfile
    session_id: Optional[str] = None


class ResearchResponse(BaseModel):
    """HTTP response body for POST /api/research."""
    session_id: str
    message: str
    stream_url: str
    results_url: str
    is_demo: bool
